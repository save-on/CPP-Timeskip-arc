// quickMath.h (Interface)
#ifndef QUICKMATH_H
#define QUICKMATH_H

template <typename T> T sum(T input1, T input2) { return input1 + input2; };

template <typename T> T sub(T input1, T input2) { return input1 - input2; };

template <typename T> T div(T input1, T input2);

template <typename T> T mul(T input1, T input2);

#endif
